"""Tests for the shared ``node_modules`` precondition helper (issue #2311).

``ensure_node_modules`` is a gate: it returns the skip ``ToolResult`` a caller
must hand back, or ``None`` to let the tool run. Each of its four outcomes is
covered here so the astro-check and svelte-check suites do not have to repeat
the matrix.
"""

from __future__ import annotations

from pathlib import Path
from unittest.mock import patch

from assertpy import assert_that

from lintro.tools.core.node_modules import ensure_node_modules
from lintro.tools.definitions.astro_check import AstroCheckPlugin

#: Module path the helper resolves its two node_deps functions through.
_MODULE: str = "lintro.tools.core.node_modules"


def test_an_installed_project_is_allowed_to_run(tmp_path: Path) -> None:
    """Nothing is returned when the dependencies are already on disk.

    Args:
        tmp_path: Project directory the tool would run in.
    """
    with patch(f"{_MODULE}.should_install_deps", return_value=False):
        result = ensure_node_modules(
            plugin=AstroCheckPlugin(),
            cwd=tmp_path,
            auto_install=False,
            tool_label="astro-check",
        )

    assert_that(result).is_none()


def test_a_read_only_project_is_skipped_without_failing(tmp_path: Path) -> None:
    """A directory that cannot be installed into is a skip, not an error.

    Args:
        tmp_path: Project directory the tool would run in.
    """
    with patch(
        f"{_MODULE}.should_install_deps",
        side_effect=PermissionError("read-only mount?"),
    ):
        result = ensure_node_modules(
            plugin=AstroCheckPlugin(),
            cwd=tmp_path,
            auto_install=True,
            tool_label="astro-check",
        )

    assert result is not None  # narrow type for mypy
    assert_that(result.success).is_true()
    assert_that(result.skipped).is_true()
    assert_that(result.skip_reason).is_equal_to("directory not writable")
    assert_that(result.output).contains("read-only mount?")


def test_missing_dependencies_without_auto_install_name_the_flag(
    tmp_path: Path,
) -> None:
    """The default skip tells the user which flag turns installing on.

    Args:
        tmp_path: Project directory the tool would run in.
    """
    with patch(f"{_MODULE}.should_install_deps", return_value=True):
        result = ensure_node_modules(
            plugin=AstroCheckPlugin(),
            cwd=tmp_path,
            auto_install=False,
            tool_label="astro-check",
        )

    assert result is not None  # narrow type for mypy
    assert_that(result.success).is_true()
    assert_that(result.skipped).is_true()
    assert_that(result.skip_reason).is_equal_to("node_modules not found")
    assert_that(result.output).contains("--auto-install")


def test_a_successful_auto_install_lets_the_tool_run(tmp_path: Path) -> None:
    """Installing on demand clears the gate rather than reporting a result.

    Args:
        tmp_path: Project directory the tool would run in.
    """
    with (
        patch(f"{_MODULE}.should_install_deps", return_value=True),
        patch(f"{_MODULE}.install_node_deps", return_value=(True, "")) as installer,
    ):
        result = ensure_node_modules(
            plugin=AstroCheckPlugin(),
            cwd=tmp_path,
            auto_install=True,
            tool_label="astro-check",
        )

    assert_that(result).is_none()
    installer.assert_called_once_with(tmp_path)


def test_a_failed_auto_install_skips_and_keeps_the_installer_output(
    tmp_path: Path,
) -> None:
    """The installer's own message is the only diagnosis, so it is kept.

    Args:
        tmp_path: Project directory the tool would run in.
    """
    with (
        patch(f"{_MODULE}.should_install_deps", return_value=True),
        patch(f"{_MODULE}.install_node_deps", return_value=(False, "ENOENT bun")),
    ):
        result = ensure_node_modules(
            plugin=AstroCheckPlugin(),
            cwd=tmp_path,
            auto_install=True,
            tool_label="astro-check",
        )

    assert result is not None  # narrow type for mypy
    assert_that(result.success).is_true()
    assert_that(result.skip_reason).is_equal_to("auto-install failed")
    assert_that(result.output).contains("ENOENT bun")


def test_the_tool_label_names_the_tool_in_the_skip_message(tmp_path: Path) -> None:
    """The user-facing spelling comes from the label, not the registered name.

    Args:
        tmp_path: Project directory the tool would run in.
    """
    with (
        patch(f"{_MODULE}.should_install_deps", return_value=True),
        patch(f"{_MODULE}.install_node_deps", return_value=(False, "boom")),
    ):
        result = ensure_node_modules(
            plugin=AstroCheckPlugin(),
            cwd=tmp_path,
            auto_install=True,
            tool_label="svelte-check",
        )

    assert result is not None  # narrow type for mypy
    assert_that(result.output).starts_with("Skipping svelte-check:")
