"""Shared ``node_modules`` precondition for Node-based tool definitions.

``astro-check`` and ``svelte-check`` are shipped inside the project they lint,
so neither can run until the project's dependencies are on disk. Both
definitions carried the same three-way decision before building their command:
skip when the directory is read-only, install when ``--auto-install`` is set,
and otherwise skip with the instruction to pass that flag. This module holds
that decision once.

Example:
    >>> skip = ensure_node_modules(  # doctest: +SKIP
    ...     plugin=self,
    ...     cwd=cwd_path,
    ...     auto_install=bool(merged_options.get("auto_install", False)),
    ...     tool_label="astro-check",
    ... )
    >>> if skip is not None:  # doctest: +SKIP
    ...     return skip
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from loguru import logger

from lintro.models.core.tool_result import ToolResult
from lintro.utils.node_deps import install_node_deps, should_install_deps

if TYPE_CHECKING:
    from pathlib import Path

    from lintro.plugins.base import BaseToolPlugin

__all__ = ["ensure_node_modules"]


def ensure_node_modules(
    *,
    plugin: BaseToolPlugin,
    cwd: Path,
    auto_install: bool,
    tool_label: str,
) -> ToolResult | None:
    """Make sure ``cwd`` has installed Node dependencies before a tool runs.

    Args:
        plugin: Plugin whose definition names the returned ``ToolResult``.
        cwd: Project directory the tool will run in.
        auto_install: Whether the user opted into installing missing
            dependencies rather than being told to.
        tool_label: Human-facing tool name used in log lines and skip
            messages (for example ``"astro-check"``).

    Returns:
        A skip ``ToolResult`` the caller must return immediately, or ``None``
        when the tool may proceed.
    """
    try:
        needs_install = should_install_deps(cwd)
    except PermissionError as exc:
        logger.warning("[{}] {}", tool_label, exc)
        return ToolResult(
            name=plugin.definition.name,
            success=True,
            output=f"Skipping {tool_label}: {exc}",
            issues_count=0,
            skipped=True,
            skip_reason="directory not writable",
        )

    if not needs_install:
        return None

    if not auto_install:
        return ToolResult(
            name=plugin.definition.name,
            output=(
                "node_modules not found. Use --auto-install to install dependencies."
            ),
            issues_count=0,
            skipped=True,
            skip_reason="node_modules not found",
        )

    logger.info("[{}] Auto-installing Node.js dependencies...", tool_label)
    install_ok, install_output = install_node_deps(cwd)
    if install_ok:
        logger.info("[{}] Dependencies installed successfully", tool_label)
        return None

    logger.warning("[{}] Auto-install failed, skipping: {}", tool_label, install_output)
    return ToolResult(
        name=plugin.definition.name,
        success=True,
        output=f"Skipping {tool_label}: auto-install failed.\n{install_output}",
        issues_count=0,
        skipped=True,
        skip_reason="auto-install failed",
    )
